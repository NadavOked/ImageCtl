# נוספים ב-imagectl-dhcp.conf אם יודלק DHCP על כרטיס אחר.
$DNSMASQ_IFACE_LINES

enable-tftp
tftp-root=$TFTP_ROOT
# אין צורך לקבוע גודל בלוק: ‏dnsmasq נענה אוטומטית ל-blksize שהלקוח
