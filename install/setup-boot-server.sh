        # מצמידה כתובת, לא שם — פותרים עכשיו ואומרים זאת: ראשי שמקבל DHCP
        # בלי reservation יחליף כתובת והכלל יתיישן.
        if [[ ! "$PRIMARY_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
