#!/usr/bin/env bash
#
# ImageCtl — התקנה מלאה על שרת דביאן: שרשרת האתחול, השרת והקונסולה.
#
# הרצה אחת, כמה שאלות, וזהו:
#   1. איזה כרטיס לוילן השרתים (קונסולה/SSH) — ברירת המחדל: לקוח DHCP
#      של המכללה (#1088); סטטי = בחירה, אותן שאלות כמו בקונסולה
#   2. איזה כרטיס להפצה — או "לא עכשיו" (ברירת המחדל במסירה, #1088):
#      המנהל בוחר אותו מהקונסולה (דף הרשת: כתובת → DHCP), וזה משלים
#      את מה שהמתקין היה כותב כאן
# המנהל כברירת מחדל הוא admin/admin עם החלפה כפויה בקונסולה (#1085).
# `--admin-user` / `--admin-pass` נשארים לדיבאג — ואז בלי כפייה.
#
#   sudo ./setup-boot-server.sh
#
# כל השאר בקונסולה: DHCP לכל כרטיס (לשונית הרשת, אפיון סעיף 24),
# בדיקות מצב (מסך הבריאות). הטרמינל נוגעים בו פעם אחת — כאן.
#
# ראו docs/server-install.md להסבר מלא.

set -euo pipefail

# ---------------------------------------------------------------------------
# ברירות מחדל (הדגלים כולם רשות — לאוטומציה ולדיבאג, לא לזרימה הרגילה)
# ---------------------------------------------------------------------------

SERVER_URL=""
IFACE=""
IFACE_FROM_FLAG=0
SERVERS_IF=""
SERVERS_IF_FROM_FLAG=0
# ‏#1088: כרטיס השרתים — לקוח DHCP (ברירת מחדל) או סטטי; ‏DNS מופרד בפסיקים.
SERVERS_MODE="dhcp"
SERVERS_ADDR=""
SERVERS_MASK="255.255.255.0"
SERVERS_GW=""
SERVERS_DNS=""
NO_FIREWALL=0
ADMIN_USER=""
ADMIN_PASS=""
# Storage Nodes (#655/#723): תפקיד ההתקנה. standalone (ברירת מחדל) או
# secondary. משני מחייב כתובת שרת ראשי. **תצורת שרת בלבד** — לא נכנס
# לשורת הפקודה של הקרנל (עיקרון 2). מועבר ל-server.main דרך היחידה.
STORAGE_ROLE="standalone"
PRIMARY_URL=""
# ‏#703 (tracer 5): כתובת כרטיס הניהול שעליה הקונסולה (8081, HTTPS) מאזינה.
# ‏#1088: ריק = כרטיס השרתים שנבחר, **לפי שם** (השרת עוקב אחרי הכתובת
# שה-DHCP נותן). התעודה נוצרת כאן בכל מקרה, לפני ההרמה.
CONSOLE_HOST=""
TFTP_ROOT="/srv/tftp"
HTTP_ROOT="/srv/imagectl/boot"
APP_DIR="/opt/imagectl"
DATA_DIR="/var/lib/imagectl"
IMAGES_DIR="/srv/imagectl/images"
# הריפו שונה שמו ל-ImageCtl-archive ב-09/2026 והפך לפרטי; השם הישן
# `NadavOked/ImageCtl` שייך היום לפרויקט אחר, ו-clone ממנו היה מתקין
# קוד זר על שרת האתחול בלי להתלונן. ‏clone מהארכיון דורש אישורים
# ונכשל בקול — וזה המצב הרצוי מבין השניים.
REPO_URL="https://github.com/NadavOked/ImageCtl-archive"
DRY_RUN=0
PORT=8080

# ---------------------------------------------------------------------------
# הקובץ הקבוע ל-GRUB
# ---------------------------------------------------------------------------
#
# מוטמע כאן כדי שהסקריפט יעבוד גם בלי הריפו. המקור האמיתי הוא
# boot/grub_menu.py:render_bootstrap(); הטסט
# tests/test_installer_matches_generator.py משווה בין השניים.

read -r -d '' GRUB_BOOTSTRAP <<'GRUBCFG' || true
# ImageCtl bootstrap - generated by boot/grub_menu.py:render_bootstrap().
# Lives on the TFTP root as grub/grub.cfg. Regenerate, do not hand-edit.

set pager=0
set timeout=0
set timeout_style=hidden

# efinet exists only on UEFI; the i386-pc netboot core (the cloning
# machines, #38) has its driver built in, and insmod-ing a module that
# does not exist prints an error on the boot screen.
if [ "$grub_platform" = "efi" ]; then insmod efinet; fi
insmod http
insmod tftp

function try_chain {
    unset espdev
    search --no-floppy --file --set=espdev "$1"
    if [ -n "$espdev" ]; then
        set root=$espdev
        if chainloader "$1"; then
            boot
        else
            if [ -z "$chain_refused" ]; then set chain_refused=$1; fi
        fi
    fi
}

function chain_local {
    insmod part_gpt
    insmod fat
    insmod chain
    insmod search_fs_file
    unset chain_refused

    for path in /EFI/Microsoft/Boot/bootmgfw.efi /EFI/ubuntu/shimx64.efi /EFI/ubuntu/grubx64.efi /EFI/debian/shimx64.efi /EFI/debian/grubx64.efi /EFI/fedora/shimx64.efi /EFI/fedora/grubx64.efi /EFI/centos/shimx64.efi /EFI/rocky/shimx64.efi /EFI/almalinux/shimx64.efi /EFI/opensuse/shim.efi /EFI/BOOT/bootx64.efi; do
        try_chain "$path"
    done

    echo ""
    if [ -n "$chain_refused" ]; then
        echo "A boot loader WAS found on the local disk:"
        echo "  $chain_refused"
        echo "but this menu was refused permission to start it (see the error above)."
        if [ "$shim_lock" = "y" ]; then
            echo "Why: Secure Boot is on. Every chainload from this menu is checked"
            echo "by shim, and shim did not accept this file's signature."
            echo "The disk and the operating system are most likely intact."
            echo "To start it now: power off, then boot from the disk directly"
            echo "(firmware boot menu, usually F12), bypassing PXE."
        else
            echo "Why: unknown. GRUB does not report a shim lock, so this is"
            echo "not a Secure Boot refusal. Read the error above."
        fi
    else
        echo "No operating system found on the local disk."
    fi
    echo "Contact IT. This computer will stay powered on."
    set stay_on=y
    while [ "$stay_on" = "y" ]; do
        sleep --interruptible 60
    done
}

function try_local {
    if [ "$grub_platform" = "efi" ]; then
        echo "Booting from the local disk."
        chain_local
    fi

    echo ""
    echo "This machine booted in Legacy BIOS mode, which on this network"
    echo "means a cloning machine. It has no local system to start, and the"
    echo "drives attached to it are the payload - they are never booted from."
    echo "Nothing will be started."
    echo "Fix the server or the network, then power-cycle this machine."
    echo "Contact IT. This computer will stay powered on."
    set stay_on=y
    while [ "$stay_on" = "y" ]; do
        sleep --interruptible 60
    done
}

# GRUB fills net_default_mac from the interface that PXE-booted, already in
# lowercase-with-colons form -- the canonical format from the interface spec.
if [ -z "$net_default_mac" ]; then
    echo "ImageCtl: no network interface reported."
    sleep --interruptible 3
    try_local
fi

# Deployment address. net_default_server -- the DHCP or PXE-proxy server that
# actually answered this station -- comes first, because it is the only address
# that is right on every network: a station booted by a proxy on a foreign VLAN
# (spec scenario 3) often cannot reach the deployment VLAN address at all. The
# port is not in DHCP, so it comes from the configured address.
# The explicit address stays as a fallback, for debugging and for the case
# where next-server arrives empty or points at a machine without ImageCtl.
set imagectl_fallback=@@GRUB_HOST@@
if [ -n "$net_default_server" ]; then
    set imagectl_server=${net_default_server}:@@GRUB_PORT@@
else
    set imagectl_server=$imagectl_fallback
fi

# Three attempts: GRUB's EFI http stack sometimes fails its very first
# connection on a cold boot while TFTP already works (#31). A retry a
# second later succeeds; only a server that is really down falls through.
# Each attempt also tries the fallback, unless it is the same address.
for attempt in 1 2 3; do
    configfile (http,$imagectl_server)/boot/menu?mac=$net_default_mac
    if [ "$imagectl_server" != "$imagectl_fallback" ]; then
        configfile (http,$imagectl_fallback)/boot/menu?mac=$net_default_mac
    fi
    sleep 1
done

# Reached only if every fetch failed -- server down, cable out, DHCP wrong.
# try_local, not chain_local: this file runs before the machine has asked
# about its own MAC, so it cannot know it is a cloning machine -- and with
# the server down there is nobody to ask. $grub_platform is the one thing
# it does know (#323).
echo "ImageCtl: server $imagectl_server unreachable."
sleep --interruptible 3
try_local
GRUBCFG

# ---------------------------------------------------------------------------
# עזרים
# ---------------------------------------------------------------------------

RED=$'\033[31m'; YEL=$'\033[33m'; GRN=$'\033[32m'; DIM=$'\033[2m'; OFF=$'\033[0m'

say()  { printf '%s==>%s %s\n' "$GRN" "$OFF" "$*"; }
warn() { printf '%s[!]%s %s\n' "$YEL" "$OFF" "$*" >&2; }
die()  { printf '%s[x]%s %s\n' "$RED" "$OFF" "$*" >&2; exit 1; }

run() {
    if (( DRY_RUN )); then
        printf '%s    would run: %s%s\n' "$DIM" "$*" "$OFF"
    else
        "$@"
    fi
}

write_file() {
    # write_file <path> <<'EOF' ... EOF
    local path="$1" content
    content="$(cat)"
    if (( DRY_RUN )); then
        printf '%s    would write %s (%d bytes)%s\n' "$DIM" "$path" "${#content}" "$OFF"
        return
    fi
    install -d "$(dirname "$path")"
    if [[ -f "$path" ]] && ! grep -q "ImageCtl" "$path" 2>/dev/null; then
        # קובץ שלא אנחנו כתבנו — מגבים במקום לדרוס.
        cp -a "$path" "${path}.pre-imagectl.$(date +%Y%m%d%H%M%S)"
        warn "backed up existing $path"
    fi
    printf '%s\n' "$content" > "$path"
}

usage() {
    cat <<'EOF'
ImageCtl — התקנה מלאה על שרת דביאן: שרשרת אתחול, שרת וקונסולה.

  sudo ./setup-boot-server.sh

ההתקנה שואלת על כרטיס וילן השרתים (לקוח DHCP של המכללה כברירת מחדל,
או סטטי — #1088), על כרטיס ההפצה (או "לא עכשיו" — המנהל יבחר אותו
מהקונסולה), ומרימה הכל — כולל חומת אש nftables לפי וילן (#1074). המנהל
הוא admin/admin עם החלפה כפויה בקונסולה (#1085); --admin-pass לדיבאג.
DHCP לא נדלק כאן בכלל — מגדירים אותו אחר כך מהקונסולה, לשונית הרשת,
עם כל שכבות הבטיחות (אפיון סעיף 24). בלי כרטיס הפצה dnsmasq אינו מופעל
ו-grub.cfg אינו נכתב — ההדלקה מהקונסולה משלימה את שניהם.

דגלים (רשות — לאוטומציה ולדיבאג בלבד):
  --deploy-if IFACE    כרטיס ההפצה (מדלג על השאלה); --interface הוא שם ישן לאותו דגל
  --servers-if IFACE   כרטיס וילן השרתים (קונסולה 8081, SSH); בלי דגל — נשאל, או = כרטיס ההפצה באוטומציה
  --servers-mode MODE  dhcp (ברירת מחדל) או static לכרטיס השרתים (#1088)
  --servers-address A  --servers-netmask M  --servers-gateway G  --servers-dns D1,D2
                       פרטי הכתובת הסטטית לכרטיס השרתים (עם --servers-mode static)
  --no-firewall        מדלג על nftables, עם אזהרה ביומן (R20-F1)
  --server-url URL     עוקף את הכתובת הנגזרת מהכרטיס (http בלבד)
  --admin-user NAME    מדלג על שאלת המשתמש
  --admin-pass PASS    מדלג על שאלות הסיסמה (נשאר בהיסטוריית השלל — לדיבאג)
  --tftp-root PATH     ברירת מחדל /srv/tftp
  --http-root PATH     ברירת מחדל /srv/imagectl/boot; מועבר לשרת כ---boot-dir
  --storage-role ROLE  standalone (ברירת מחדל) או secondary (#655/#723)
  --primary-url URL    כתובת השרת הראשי — חובה ל-secondary
  --console-host ADDR  כתובת/שם כרטיס הניהול לקונסולה (8081, HTTPS); ברירת מחדל: כרטיס השרתים לפי שם (#1088)
  --dry-run            מראה מה יקרה בלי לשנות כלום
  -h, --help           המסך הזה
EOF
}

# ---------------------------------------------------------------------------
# פירוק ארגומנטים
# ---------------------------------------------------------------------------

while [[ $# -gt 0 ]]; do
    case "$1" in
        --interface|--deploy-if) IFACE="${2:?}"; IFACE_FROM_FLAG=1; shift 2 ;;
        --servers-if)  SERVERS_IF="${2:?}"; SERVERS_IF_FROM_FLAG=1; shift 2 ;;
        --servers-mode) SERVERS_MODE="${2:?}"; shift 2 ;;
        --servers-address) SERVERS_ADDR="${2:?}"; shift 2 ;;
        --servers-netmask) SERVERS_MASK="${2:?}"; shift 2 ;;
        --servers-gateway) SERVERS_GW="${2:?}"; shift 2 ;;
        --servers-dns) SERVERS_DNS="${2:?}"; shift 2 ;;
        --no-firewall) NO_FIREWALL=1; shift ;;
        --server-url)  SERVER_URL="${2:?}"; shift 2 ;;
        --admin-user)  ADMIN_USER="${2:?}"; shift 2 ;;
        --admin-pass)  ADMIN_PASS="${2:?}"; shift 2 ;;
        --tftp-root)   TFTP_ROOT="${2:?}"; shift 2 ;;
        --http-root)   HTTP_ROOT="${2:?}"; shift 2 ;;
        --storage-role) STORAGE_ROLE="${2:?}"; shift 2 ;;
        --primary-url) PRIMARY_URL="${2:?}"; shift 2 ;;
        --console-host) CONSOLE_HOST="${2:?}"; shift 2 ;;
        --dry-run)     DRY_RUN=1; shift ;;
        -h|--help)     usage; exit 0 ;;
        --mode|--dhcp-range)
            die "הדגל $1 בוטל: DHCP מוגדר מהקונסולה, לשונית הרשת (אפיון סעיף 24)." ;;
        *)             die "unknown option: $1  (try --help)" ;;
    esac
done

(( DRY_RUN )) || [[ $EUID -eq 0 ]] || die "צריך להריץ עם sudo (או --dry-run כדי רק לראות)."

# ---------------------------------------------------------------------------
# שאלה 1 — כרטיס וילן השרתים (קונסולה 8081, SSH 22), מתוך רשימה של מה שקיים
# ---------------------------------------------------------------------------
#
# ‏#1088: הכרטיס הזה הוא לקוח DHCP של המכללה כברירת מחדל — הכתובת מגיעה
# מה-DHCP של רשת השרתים, ו-`hostname` (אופציה 12) נשלח כדי שה-DNS שם
# יפתור את שם השרת. הקונסולה נקשרת אליו **לפי שם** (--console-host <if>)
# ומאזינה מחדש כשהכתובת משתנה. סטטי הוא בחירה, באותן שאלות כמו בקונסולה.

iface_ip() { ip -4 -o addr show dev "$1" 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1; }

list_nics() {
    mapfile -t NICS < <(ip -br link | awk '$1 != "lo" {print $1}' | cut -d@ -f1)
    (( ${#NICS[@]} )) || die "לא נמצאו כרטיסי רשת."
    for i in "${!NICS[@]}"; do
        n="${NICS[$i]}"
        state="$(cat "/sys/class/net/$n/operstate" 2>/dev/null || echo '?')"
        printf '  %d) %-12s %-6s %s\n' "$((i + 1))" "$n" "$state" "$(iface_ip "$n")"
    done
}

if [[ -z "$SERVERS_IF" ]]; then
    if (( IFACE_FROM_FLAG )); then
        # אוטומציה (--deploy-if בלי --servers-if): אותו כרטיס, כדי לא לשבור סקריפטים.
        SERVERS_IF="$IFACE"
    else
        say "כרטיס וילן השרתים (קונסולה HTTPS, SSH ניהול):"
        list_nics
        read -r -p "על איזה כרטיס וילן השרתים? [1]: " pick
        pick="${pick:-1}"
        [[ "$pick" =~ ^[0-9]+$ ]] && (( pick >= 1 && pick <= ${#NICS[@]} ))             || die "אין כרטיס מספר $pick ברשימה."
        SERVERS_IF="${NICS[$((pick - 1))]}"
        read -r -p "כתובת לכרטיס השרתים — DHCP מהמכללה (d) או סטטית (s)? [d]: " mode_pick
        case "${mode_pick:-d}" in
            d|D|dhcp)   SERVERS_MODE="dhcp" ;;
            s|S|static) SERVERS_MODE="static"
                        read -r -p "  כתובת: " SERVERS_ADDR
                        read -r -p "  מסכה [255.255.255.0]: " SERVERS_MASK
                        SERVERS_MASK="${SERVERS_MASK:-255.255.255.0}"
                        read -r -p "  שער (ריק = בלי): " SERVERS_GW
                        read -r -p "  DNS (מופרד בפסיקים, ריק = בלי): " SERVERS_DNS ;;
            *)          die "תשובה לא מוכרת: $mode_pick (d או s)" ;;
        esac
    fi
fi
ip link show "$SERVERS_IF" >/dev/null 2>&1 || die "לא קיים ממשק בשם $SERVERS_IF"
case "$SERVERS_MODE" in
    dhcp)   ;;
    static) [[ -n "$SERVERS_ADDR" ]] || die "כרטיס שרתים סטטי מחייב כתובת (--servers-address)" ;;
    *)      die "--servers-mode חייב להיות dhcp או static (התקבל: $SERVERS_MODE)" ;;
esac

# ---------------------------------------------------------------------------
# שאלה 2 — כרטיס ההפצה, או "לא עכשיו" (#1088)
# ---------------------------------------------------------------------------
#
# במסירה למכללה רשת ההפצה **אינה מוגדרת** כאן: המנהל בוחר את הכרטיס מדף
# הרשת בקונסולה, קובע לו כתובת סטטית ומדליק DHCP — וההדלקה משלימה כל מה
# שהמתקין היה כותב לכרטיס ההפצה (grub.cfg, dnsmasq באתחול, חומת אש,
# והכתובת ליחידה). בלי כרטיס הפצה: dnsmasq לא מופעל, grub.cfg לא נכתב,
# והשרת עולה במצב "רשת ההפצה לא הוגדרה" (הסוכן על loopback בלבד).

# באוטומציה (--servers-if בלי --deploy-if) אין שאלה: "לא עכשיו".
if [[ -z "$IFACE" && ! $SERVERS_IF_FROM_FLAG -eq 1 ]]; then
    say "כרטיס ההפצה (DHCP/TFTP/מולטיקאסט למחשבי השיכפול והבנייה):"
    printf '  0) לא עכשיו — המנהל יבחר אותו מהקונסולה (דף הרשת)\n'
    list_nics
    read -r -p "על איזה כרטיס תוגדר רשת ההפצה? [0]: " pick
    pick="${pick:-0}"
    if [[ "$pick" == "0" ]]; then
        IFACE=""
    else
        [[ "$pick" =~ ^[0-9]+$ ]] && (( pick >= 1 && pick <= ${#NICS[@]} ))             || die "אין כרטיס מספר $pick ברשימה."
        IFACE="${NICS[$((pick - 1))]}"
    fi
fi
if [[ -n "$IFACE" ]]; then
    ip link show "$IFACE" >/dev/null 2>&1 || die "לא קיים ממשק בשם $IFACE"
    # הכתובת נגזרת מהכרטיס — אין סיבה להקליד אותה.
    if [[ -z "$SERVER_URL" ]]; then
        ADDR="$(iface_ip "$IFACE")"
        [[ -n "$ADDR" ]] || die "לכרטיס $IFACE אין כתובת IP.
    קבעו לו כתובת סטטית (זה שרת) והריצו שוב — או בחרו 'לא עכשיו' והגדירו מהקונסולה."
        SERVER_URL="http://$ADDR:$PORT"
    fi
elif [[ -n "$SERVER_URL" ]]; then
    die "--server-url בלי כרטיס הפצה (--deploy-if) — הכתובת חייבת לשבת על כרטיס"
fi
# ‏#1088: ‏--console-host ברירת מחדל = כרטיס השרתים **לפי שם** — השרת פותר
# את הכתובת בעלייה ומאזין מחדש בהחלפתה. כתובת מפורשת (הדגל) גוברת.
CONSOLE_HOST="${CONSOLE_HOST:-$SERVERS_IF}"

case "$SERVER_URL" in
    "")        ;;   # #1088: אין כרטיס הפצה עדיין — הכתובת תיקבע מהקונסולה
    http://*)  ;;
    https://*) die "https לא נתמך: ה-GRUB החתום של דביאן נבנה בלי TLS. השתמש ב-http." ;;
    *)         die "--server-url חייב להתחיל ב-http:// (התקבל: $SERVER_URL)" ;;
