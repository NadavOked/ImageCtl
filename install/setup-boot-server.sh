# #141: dhcp-hostsfile למטה מצביע על קובץ הזה — אם הוא לא קיים, dnsmasq
# מסרב לעלות (וה-restart שאחרי ה-heredoc נכשל, לפני שהשרת עצמו רץ אפילו
# פעם אחת ויכול לכתוב אותו). placeholder ריק זהה למה שהשרת כותב בעצמו
# כשאין אף מכונה רשומה (dhcp.render_known_macs([])) — הוא נדרס בפעם
# הראשונה שהשרת עולה או שמכונה נוספת מהקונסולה.
write_file /etc/imagectl/known-macs <<'EOF'
# ImageCtl -- registered MAC addresses, generated from the console (#141).
# Do not edit by hand: the next machine add/edit/delete rewrites it.
EOF
